"""Execute every notebook cell with IPython in-process and export its real outputs."""
from pathlib import Path
import os
import nbformat
from nbconvert import HTMLExporter
from IPython.core.interactiveshell import InteractiveShell
from IPython.utils.capture import capture_output
ROOT=Path(__file__).resolve().parents[1]
os.chdir(ROOT)
n=nbformat.read(ROOT/'notebooks/reproduce_paper.ipynb',as_version=4)
shell=InteractiveShell.instance()
count=0
for cell in n.cells:
 if cell.cell_type!='code':continue
 count+=1;cell.outputs=[];cell.execution_count=count
 with capture_output() as captured:
  result=shell.run_cell(cell.source,store_history=True)
  result.raise_error()
 if captured.stdout:cell.outputs.append(nbformat.v4.new_output('stream',name='stdout',text=captured.stdout))
 if captured.stderr:cell.outputs.append(nbformat.v4.new_output('stream',name='stderr',text=captured.stderr))
 for output in captured.outputs:
  cell.outputs.append(nbformat.v4.new_output('display_data',data=output.data,metadata=output.metadata))
 print(f'Executed cell {count}',flush=True)
n.metadata['execution_method']='IPython in-process; all outputs are generated by the supplied code'
nbformat.validate(n)
nbformat.write(n,ROOT/'notebooks/reproduce_paper.ipynb')
html,_=HTMLExporter().from_notebook_node(n)
(ROOT/'outputs/reproduce_paper.html').write_text(html)
print('Notebook executed without errors')
